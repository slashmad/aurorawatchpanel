// Builds a Font Awesome Free subset containing only the icons the dashboard
// uses, into the git-ignored app/static/vendor/fontawesome/.
//
// The full kit was ~22 KB of render-blocking CSS plus a 153 KB font from a
// third-party CDN, for about 30 icons. Icons are found by scanning index.html
// and the JavaScript sources for `fa-<name>` classes, so a newly used icon is
// picked up automatically; an unknown or non-free-solid name fails the build.
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const subsetFont = require('subset-font');

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fa = join(root, 'node_modules', '@fortawesome', 'fontawesome-free');
const target = join(root, 'app', 'static', 'vendor', 'fontawesome');
const staticDir = join(root, 'app', 'static');

// Utility classes, not icons.
const MODIFIERS = new Set([
  'solid', 'regular', 'brands', 'classic', 'sharp', 'fw', 'lg', 'xs', 'sm', 'xl', '2xs', '2xl',
  'spin', 'spin-pulse', 'spin-reverse', 'pulse', 'beat', 'beat-fade', 'bounce', 'fade', 'flip',
  'shake', 'border', 'inverse', 'li', 'ul', 'pull-left', 'pull-right', 'stack', 'stack-1x', 'stack-2x',
  'rotate-90', 'rotate-180', 'rotate-270', 'rotate-by', 'flip-horizontal', 'flip-vertical', 'flip-both',
  'width-auto', 'width-fixed',
]);

function sources() {
  const js = readdirSync(join(staticDir, 'js'))
    .filter(f => f.endsWith('.js') && f !== 'main.min.js')
    .map(f => join(staticDir, 'js', f));
  return [join(staticDir, 'index.html'), ...js];
}

function usedIconNames() {
  const names = new Set();
  for (const file of sources()) {
    for (const [, name] of readFileSync(file, 'utf8').matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) {
      if (!MODIFIERS.has(name) && !/^\d+x$/.test(name)) names.add(name);
    }
  }
  return [...names].sort();
}

const pinned = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).dependencies['@fortawesome/fontawesome-free'];
const installed = JSON.parse(readFileSync(join(fa, 'package.json'), 'utf8')).version;
if (installed !== pinned) {
  console.error(`@fortawesome/fontawesome-free ${installed} is installed but package.json pins ${pinned}; run npm ci.`);
  process.exit(1);
}

const families = JSON.parse(readFileSync(join(fa, 'metadata', 'icon-families.json'), 'utf8'));
const byAlias = new Map();
for (const [name, icon] of Object.entries(families)) {
  for (const alias of icon.aliases?.names || []) byAlias.set(alias, name);
}

const icons = [];
const problems = [];
for (const used of usedIconNames()) {
  const canonical = families[used] ? used : byAlias.get(used);
  const icon = canonical && families[canonical];
  const freeSolid = icon?.familyStylesByLicense?.free?.some(s => s.family === 'classic' && s.style === 'solid');
  if (!icon) problems.push(`fa-${used}: not a Font Awesome ${installed} icon`);
  else if (!freeSolid) problems.push(`fa-${used}: not available in the free solid style`);
  else icons.push({ cls: used, unicode: icon.unicode });
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const text = String.fromCodePoint(...icons.map(i => parseInt(i.unicode, 16)));
const font = await subsetFont(readFileSync(join(fa, 'webfonts', 'fa-solid-900.woff2')), text, { targetFormat: 'woff2' });
const fontHash = createHash('sha256').update(font).digest('hex').slice(0, 10);

const css = `/*! Font Awesome Free ${installed} subset (${icons.length} icons) by @fontawesome - https://fontawesome.com
 * License: https://fontawesome.com/license/free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT License)
 * Copyright 2023 Fonticons, Inc. Generated by scripts/vendor-fontawesome.mjs; do not edit. */
@font-face{font-family:"Font Awesome 6 Free";font-style:normal;font-weight:900;font-display:block;src:url(fa-solid-900.subset.woff2?v=${fontHash}) format("woff2")}
.fa,.fa-solid,.fas{font-family:"Font Awesome 6 Free";font-weight:900;-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}
.fa-spin{animation:fa-spin var(--fa-animation-duration,2s) linear infinite}
@keyframes fa-spin{0%{transform:rotate(0)}to{transform:rotate(1turn)}}
${icons.map(i => `.fa-${i.cls}:before{content:"\\${i.unicode}"}`).join('\n')}
`;

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
writeFileSync(join(target, 'fa-solid-900.subset.woff2'), font);
writeFileSync(join(target, 'fontawesome-subset.css'), css);
writeFileSync(join(target, 'LICENSE.txt'), readFileSync(join(fa, 'LICENSE.txt')));
console.log(`Font Awesome ${installed}: ${icons.length} icons, font ${font.length} B, css ${css.length} B -> app/static/vendor/fontawesome/`);
